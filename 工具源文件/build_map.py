def norm(t):
    t=t.strip()
    t=re.sub(r'^[^：:]{0,12}[：:]','',t)
    t=re.sub(r'[（(][^）)]*[）)]','',t)
    t=re.sub(r'^\d{4,6}[TK]{0,2}','',t)
    t=re.sub(r'[TK]$','',t)
    t=re.sub(r'含.*$|不含.*$|以上.*$|等.*$','',t)
    return t.strip()

cov=0; unc=collections.Counter()
for m in a['专业'].astype(str):
    toks=[x for x in re.split(r'[、，,；;/。]+',m) if x.strip()]
    ok=False
    for t in toks:
        n=norm(t)
        if not n or len(n)<2: continue
        if n in ALL_CATS or n in ALL_NAMES or (n.endswith('类') and n[:-1] in ALL_NAMES): ok=True;break
        if re.fullmatch(r'\d{4,6}',n): ok=True;break
        if guess_disc(n): ok=True;break
    if ok: cov+=1
    else:
        for t in toks:
            n=norm(t)
            if n and len(n)>=2: unc[n]+=1
print()
